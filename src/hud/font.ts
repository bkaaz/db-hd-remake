/** A letter's cell: five dots and a gap. */
const ADVANCE = 6;

/** How wide `text` is drawn, in pixels. */
export function textWidth(text: string): number {
  return text.length * ADVANCE - 1;
}

/** The dots `text` lights, from its top left; a character the font lacks is a space. */
export function textDots(text: string): [number, number][] {
  const dots: [number, number][] = [];
  [...text.toUpperCase()].forEach((ch, i) => {
    GLYPHS[ch]?.split(" ").forEach((row, y) => [...row].forEach((bit, x) => bit === "1" && dots.push([i * ADVANCE + x, y])));
  });
  return dots;
}

